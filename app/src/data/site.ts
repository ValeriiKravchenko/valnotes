export interface Skill {
  name: string
  level: string
  note: string
}

/** Страница внутри раздела — карточка на главной и в списке раздела (Library/Simulators). */
export interface SectionPage {
  title: string
  tag: string
  /** статус-пометка рядом с карточкой (например, «доступно»); не у всех разделов есть — см. simulatorGroups */
  status?: string
  desc: string
  href: string
}

/** Карточка тренажёра внутри группы на странице /simulators. */
export interface SimulatorCard {
  title: string
  tag: string
  desc: string
  href: string
  /** номер раздела внутри группы Git — по порядку прохождения, 1..5; в остальных группах не используется */
  sectionNumber?: number
  /** короткая пометка у карточки, например «не сверено с git» у черновика */
  note?: string
}

/**
 * Группа карточек на странице /simulators — с собственным заголовком и строкой
 * пояснения над карточками. Единственное место, где перечислены группы и их
 * карточки; новая карточка добавляется строкой в нужной группе.
 */
export interface SimulatorGroup {
  heading: string
  intro: string
  cards: SimulatorCard[]
}

/**
 * Раздел сайта — Библиотека или Симуляторы. Единственное место, где перечислены
 * разделы и их страницы: шапка (пункты навигации) и главная (оглавление)
 * строятся из этого списка, а не дублируют его у себя.
 */
export interface Section {
  slug: string
  /** подпись пункта навигации в шапке, без заглавной буквы — по образцу существующих подписей */
  navLabel: string
  heading: string
  href: string
  intro: string
  pages: SectionPage[]
}

