const TRAINER_MARKER = '[тренажёр]'

/**
 * Склонение слова «коммит» по числу — см. spec 2.7 (S1-100): «0 коммитов, 1 коммит,
 * 2–4 коммита, 5–20 коммитов, 21 коммит и т. д.» Это правило языка, а не поведения git,
 * поэтому оно живёт здесь, а не в движке.
 */
function pluralCommits(n: number): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return `${n} коммит`
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return `${n} коммита`
  return `${n} коммитов`
}

