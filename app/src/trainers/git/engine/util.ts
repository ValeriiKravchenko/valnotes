import type { FileTree } from './types'

/** `Object.prototype.hasOwnProperty` как функция — используется для различения "ключа нет"
 * от "ключ есть, но значение undefined/falsy" в FileTree и подобных плоских картах. */
export function has(obj: Record<string, unknown>, key: string): boolean {
  return Object.prototype.hasOwnProperty.call(obj, key)
}

/**
 * Простая детерминированная хэш-функция от строки (FNV-1a, 32 бита) — см. target.md, A5.
 * Не криптографическая и не обязана быть устойчивой к коллизиям: единственное требование —
 * одинаковый вход даёт одинаковый выход, а разное содержимое обычно даёт разный.
 * Возвращает ровно 7 шестнадцатеричных символов.
 */
export function hashString(input: string): string {
  let h = 0x811c9dc5
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0).toString(16).padStart(8, '0').slice(0, 7)
}

/**
 * Идентификатор коммита — хэш от содержимого (сообщение, состав файлов, родители — 0/1/2) И
 * момента коммита (target.md, A5). Настоящий git тоже различает по автору/времени два коммита с
 * одинаковым содержимым — у него это буквально часть данных коммита (committer/author +
 * timestamp), поэтому одинаковая правка с одинаковым сообщением, сделанная в разных местах
 * истории (в т.ч. в разных ветках раздела 2), почти всегда получает разные id. Здесь роль
 * «момента» играют не системные часы и не случайность (это сломало бы детерминированность тестов
 * — CLAUDE.md, «никакого состояния в глобальных переменных… ни таймеров»), а `clock` — логические
 * часы движка: счётчик шагов состояния, который вызывающая сторона (repo.ts/branchRepo.ts)
 * увеличивает на единицу при каждом новом коммите. Одинаковая последовательность действий с
 * самого начала детерминированно проходит одни и те же значения clock и даёт одинаковые id;
 * коммиты, разошедшиеся по разным веткам, — разные значения clock и разные id: два одинаковых по
 * содержимому коммита в разных ветках — это разные коммиты, а не один и тот же.
 *
 * Общая для repo.ts (раздел 1 — не больше одного родителя, оборачивается в массив из 0/1
 * элементов) и branchRepo.ts (раздел 2 — до двух родителей у коммита слияния).
 */
export function commitHashCore(message: string, tree: FileTree, parents: string[], clock: number): string {
  const filesPart = Object.keys(tree)
    .sort()
    .map((f) => `${f}\0${tree[f]}`)
    .join('\n')
  return hashString(`${parents.join(',')}\n${message}\n${filesPart}\n${clock}`)
}
