// ============================================================
// Общий для разделов 1 и 2 git-тренажёра механизм: поиск однозначного сокращения
// длинной опции (`--mess` → `--message`) и буквальный текст ошибки git при
// неоднозначном сокращении. Каждый раздел передаёт свой список опций
// (scope.ts — раздел 1, branchScope.ts — раздел 2); списков здесь нет.
// ============================================================

/**
 * Настоящий git принимает однозначные сокращения длинных опций: `--mess` работает как
 * `--message`, потому что среди опций команды это единственная, что начинается с "mess".
 * Проверено напрямую (git 2.53.0, 20.09.2026): `git commit --mess "текст"` коммитит с этим
 * сообщением — то же самое, что `git commit --message "текст"`; `git status --s` неоднозначно
 * между `--short` и `--show-stash`.
 *
 * Короткие опции ("-x") git не сокращает — это касается только длинных ("--xxx").
 *
 * @param options список длинных опций (с "--", без "=значения"), среди которых ищутся
 * кандидаты — какой именно список передать (весь набор реального git, curated-подмножество
 * и т.п.) решает вызывающий код; эта функция ничего не знает про конкретную команду.
 * @param bareName введённое сокращение целиком, например "--mess" (с "--", без "=значения").
 */
export function abbreviatedOptionCandidates(options: readonly string[], bareName: string): string[] {
  return options.filter((opt) => opt.startsWith('--') && opt.length > bareName.length && opt.startsWith(bareName))
}

/**
 * Буквальный вывод настоящего git на неоднозначное сокращение длинной опции — проверено
 * напрямую (git 2.53.0, 20.09.2026): `git status --s` → "error: ambiguous option: s (could be
 * --short or --show-stash)". Имя опции в сообщении — введённый текст БЕЗ ведущих "-", но СО
 * значением после "=", если оно было (сверено на git 2.53.0, 24.09.2026: `git branch --c=1` →
 * "error: ambiguous option: c=1 (could be --create-reflog or --column)" — "=1" остаётся в
 * сообщении, git не отрезает его, хотя сам поиск кандидатов, конечно, идёт по части до "=").
 *
 * Настоящий git выбирает пару кандидатов A/B по внутреннему порядку регистрации опций
 * parse-options.c (register_abbrev): при каждом новом совпадающем по префиксу имени опции
 * `ambiguous_option` сдвигается на `abbrev_option`, а `abbrev_option` — на нового кандидата, то
 * есть в итоговом сообщении оказываются ПОСЛЕДНИЕ ДВА совпадения в порядке объявления опций
 * (порядок, который виден в `-h`/`--git-completion-helper-all`, включая скрытые "--no-" формы —
 * они регистрируются позже основных, поэтому оказываются в конце этого порядка). Пример:
 * `git commit --a`/`--al` неоднозначны между `--allow-empty` и `--allow-empty-message` — оба
 * объявлены позже `--all`, поэтому именно они (а не `--all`, хотя это тоже реальный префикс
 * "--a") — последние два совпадения и оказываются в сообщении.
 *
 * Эта функция сама не выбирает пару — она только форматирует уже готовые `candidates` (ровно
 * два элемента, в том порядке, который получил и решил передать вызывающий код). Как выбрать
 * пару — решают вызывающие места ПО-РАЗНОМУ, и это сознательное расхождение между разделами:
 *  - classifyOption (scope.ts, раздел 1): списки опций curated и НЕ обязаны быть исчерпывающими
 *    (target.md, A10) — порядок объявления опций внутри них не совпадает с порядком настоящего
 *    git, поэтому воспроизвести "последние два по объявлению" там нечем; вместо этого берутся
 *    первые два кандидата ПО АЛФАВИТУ (target.md, часть III, A13 — сознательное упрощение: форма
 *    сообщения верна, конкретная пара кандидатов — нет, может отличаться от настоящего git);
 *  - classifySection2Option (branchScope.ts, раздел 2): списки опций ПОЛНЫЕ и в ТОЧНОМ порядке
 *    объявления (взяты из `--git-completion-helper-all`, см. шапку branchScope.ts) — этого
 *    достаточно, чтобы точно знать, что кандидатов больше одного, но не достаточно, чтобы
 *    достоверно назвать саму пару: для части случаев (особенно сокращения вида "--no-…" и пара
 *    "--verify"/"--post-rewrite" — у git это отрицания "--no-verify"/"--no-post-rewrite", и в
 *    СВОЁМ сообщении об ошибке git называет их иначе, чем видно в списке объявления) «последние
 *    два по порядку объявления» не совпадают с тем, что печатает git (git 2.53.0, 24.09.2026, см.
 *    branchCommands.test.ts). Поэтому раздел 2 не строит текст "ambiguous option: … (could be A
 *    or B)" вовсе — ни этой функцией, ни как-либо ещё — а честно отказывает без названных
 *    кандидатов (`kind: 'ambiguous'` без `output`, be.ambiguousAbbreviationOutOfScope,
 *    branchCommands.ts).
 */
export function ambiguousOptionOutput(flag: string, candidates: readonly string[]): string {
  const name = flag.replace(/^-+/, '')
  const [a, b] = candidates
  return `error: ambiguous option: ${name} (could be ${a} or ${b})`
}
