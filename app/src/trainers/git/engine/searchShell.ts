// Раздел 6 git-тренажёра, шаг A: символы шелла, которые общая модель (shell.ts)
// сознательно НЕ разбирает — перенаправления (`<`/`>`), конвейер (`|`), `;`,
// `&`, скобки подоболочки (`(`/`)`) (target.md, часть VIII, опасное место 3:
// «Модель шелла… разбирает кавычки и "*". Перенаправления… конвейер… ";"…
// "&" она не моделирует»).
//
// Раздел 6 — первый раздел, где эти символы реально встречаются в тестовых
// сценариях (шаблоны grep вроде `(fn`, `=> fn`, `renderCard\|debounce` без
// кавычек), поэтому здесь появляется отдельная проверка на "сырой" строке
// ввода — ДО shellTokenize (shell.ts), а не внутри него: сами эти символы
// шелл разбирает не так, как кавычки/"*" (перенаправление ввода-вывода,
// конвейер, список команд, подоболочка) — model shell.ts в принципе не
// пытается это симулировать. Файл НЕ меняет shell.ts (общий для разделов
// 1–5) — это независимая, отдельно вызываемая проверка.
// ============================================================

const SHELL_META = new Set(['(', ')', '<', '>', '|', ';', '&'])

/**
 * Первый символ из `( ) < > | ; &`, встреченный ВНЕ кавычек в сырой строке ввода — `null`, если
 * таких нет. Кавычками считаются только прямые `"`/`'` (тот же принцип, что и в shell.ts,
 * splitWords) — незакрытая кавычка "съедает" всё до конца строки, как и там.
 */
export function findUnquotedShellMeta(raw: string): string | null {
  let i = 0
  const n = raw.length
  while (i < n) {
    const c = raw[i]
    if (c === '"' || c === "'") {
      const quote = c
      i++
      while (i < n && raw[i] !== quote) i++
      i++ // закрывающая кавычка (если её нет — уходим за конец строки, как и splitWords)
      continue
    }
    if (SHELL_META.has(c)) return c
    i++
  }
  return null
}
