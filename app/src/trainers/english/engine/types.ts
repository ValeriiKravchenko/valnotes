// ============================================================
// Тренажёр английских слов: общие типы движка интервального повторения.
// Модуль не знает содержимого слов (перевод, транскрипция и т.п.) —
// только строковый id слова и его прогресс по системе Лейтнера.
// ============================================================

/** Ящик системы Лейтнера. 1 — самый частый показ, 5 — «выучено». */
export type Box = 1 | 2 | 3 | 4 | 5

/** Ответ игрока на показ слова. */
export type Answer = 'know' | 'dontKnow'

/** Прогресс по одному слову: текущий ящик и дата следующего показа (YYYY-MM-DD). */
export interface WordProgress {
  box: Box
  dueDate: string
}

/** Хранилище прогресса: id слова → его прогресс. Может содержать записи
 * для слов, которых нет в текущем списке id (см. правило 10) — они не
 * удаляются, но и не участвуют в сессии/статистике. */
export type ProgressStore = Record<string, WordProgress>
